-- Create the streaming table from the primary source
CREATE OR REFRESH STREAMING TABLE acme_edw_dev.edw_bronze.supplierPARTITIONED BY (snapshot_id)COMMENT "Generated by Lakehouse Plumber: write_acme_edw_dev_edw_bronze_supplier"
AS SELECT * FROM STREAM(LIVE.v_supplier_bronze_cleaned);
CREATE OR REFRESH STREAMING TABLE v_supplier_migration_bronze_cleaned_to_supplier_flow (
  COMMENT "Flow to insert data from v_supplier_migration_bronze_cleaned into supplier"
)
AS SELECT * FROM STREAM(LIVE.v_supplier_migration_bronze_cleaned);

APPLY CHANGES INTO LIVE.acme_edw_dev.edw_bronze.supplier
FROM STREAM(LIVE.v_supplier_migration_bronze_cleaned_to_supplier_flow)
KEYS()
SEQUENCE BY 1
COLUMNS *;