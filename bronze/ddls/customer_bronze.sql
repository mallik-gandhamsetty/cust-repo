-- Create the streaming table from the primary source
CREATE OR REFRESH STREAMING TABLE acme_edw_dev.edw_bronze.customerCOMMENT "Generated by Lakehouse Plumber: write_acme_edw_dev_edw_bronze_customer"
AS SELECT * FROM STREAM(LIVE.v_customer_migration_cleaned);
CREATE OR REFRESH STREAMING TABLE v_customer_bronze_DQE_to_customer_flow (
  COMMENT "Flow to insert data from v_customer_bronze_DQE into customer"
)
AS SELECT * FROM STREAM(LIVE.v_customer_bronze_DQE);

APPLY CHANGES INTO LIVE.acme_edw_dev.edw_bronze.customer
FROM STREAM(LIVE.v_customer_bronze_DQE_to_customer_flow)
KEYS()
SEQUENCE BY 1
COLUMNS *;